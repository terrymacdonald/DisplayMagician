function normalized(schema) {
  if (schema.oneOf) {
    const values = schema.oneOf.filter(item => item.type !== 'null');
    if (values.length !== 1) throw new Error('Unsupported schema union');
    return { ...values[0], nullable: schema.oneOf.some(item => item.type === 'null') };
  }
  return schema;
}
function type(schema, lang) {
  schema = normalized(schema);
  if (schema.$ref) return name(schema.$ref.split('/').at(-1));
  const kind = Array.isArray(schema.type) ? schema.type.find(value => value !== 'null') : schema.type;
  if (kind === 'array') return lang === 'swift' ? `[${type(schema.items, lang)}]` : `List<${type(schema.items, lang)}>`;
  if (kind === 'string') return 'String';
  if (kind === 'integer') return schema.format === 'int64' ? (lang === 'swift' ? 'Int64' : 'Long') : 'Int';
  if (kind === 'number') return 'Double';
  if (kind === 'boolean') return lang === 'swift' ? 'Bool' : 'Boolean';
  throw new Error('Unsupported type: ' + JSON.stringify(schema));
}
const nullable = schema => Boolean(normalized(schema).nullable || normalized(schema).type?.includes?.('null'));
function kotlinRead(schema, expression) {
  schema = normalized(schema);
  if (schema.$ref) {
    const target = schema.$ref.split('/').at(-1);
    return schemas[target].type === 'object' ? `${name(target)}.fromJson(${expression} as JSONObject)` : kotlinRead(schemas[target], expression);
  }
  const kind = Array.isArray(schema.type) ? schema.type.find(item => item !== 'null') : schema.type;
  if (kind === 'string') return `${expression} as String`;
  if (kind === 'integer') return `(${expression} as Number).${schema.format === 'int64' ? 'toLong' : 'toInt'}()`;
  if (kind === 'number') return `(${expression} as Number).toDouble()`;
  if (kind === 'boolean') return `${expression} as Boolean`;
  if (kind === 'array') return `(${expression} as JSONArray).let { array -> (0 until array.length()).map { index -> ${kotlinRead(schema.items, 'array.get(index)')} } }`;
  throw new Error('Unsupported Kotlin read');
}
function kotlinWrite(schema, expression) {
  schema = normalized(schema);
  if (schema.$ref) return schemas[schema.$ref.split('/').at(-1)].type === 'object' ? `${expression}.toJson()` : expression;
  const kind = Array.isArray(schema.type) ? schema.type.find(item => item !== 'null') : schema.type;
  return kind === 'array' ? `JSONArray(${expression}.map { value -> ${kotlinWrite(schema.items, 'value')} })` : expression;
}
